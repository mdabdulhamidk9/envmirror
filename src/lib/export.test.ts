import { describe, expect, it } from 'vitest'
import { parseEnv } from './env-parser'
import { collectUnionKeys, generateEnvExample, sanitizeKeyNames } from './export'

describe('export — sanitization', () => {
  it('keeps only syntactically safe key names', () => {
    const result = sanitizeKeyNames(['GOOD_KEY', '1BAD', 'HAS SPACE', '_ok'])
    expect(result).toEqual(['GOOD_KEY', '_ok'])
  })

  it('removes duplicate names', () => {
    expect(sanitizeKeyNames(['A', 'A', 'B'])).toEqual(['A', 'B'])
  })
})

describe('export — union collection', () => {
  it('unions keys across environments, deduplicated and sorted', () => {
    const parsed = {
      local: parseEnv('Z=1\nA=2'),
      staging: parseEnv('M=3\nA=4'),
      production: parseEnv('A=5\nB=6'),
    }
    const union = collectUnionKeys({
      local: parsed.local?.keyNames ?? [],
      staging: parsed.staging?.keyNames ?? [],
      production: parsed.production?.keyNames ?? [],
    })
    expect(union).toEqual(['A', 'B', 'M', 'Z'])
  })
})

describe('export — .env.example generation', () => {
  it('emits one KEY= line per name with empty placeholder values', () => {
    const content = generateEnvExample(['B_KEY', 'A_KEY'])
    expect(content).toBe(
      '# Generated by EnvMirror — variable names only, no secret values.\n' +
        '# Fill in a value for each variable in the target environment.\n' +
        '\n' +
        'A_KEY=\n' +
        'B_KEY=\n',
    )
  })

  it('never includes secret values', () => {
    const parsed = parseEnv('API_TOKEN=super-secret-42')
    const content = generateEnvExample(parsed.keyNames)
    expect(content).not.toContain('super-secret-42')
    expect(content).toContain('API_TOKEN=')
  })

  it('deduplicates names', () => {
    const content = generateEnvExample(['DUP', 'DUP', 'OTHER'])
    expect(content.match(/^DUP=$/gm)).toHaveLength(1)
  })

  it('uses predictable alphabetical ordering regardless of input order', () => {
    expect(generateEnvExample(['C', 'A', 'B'])).toBe(generateEnvExample(['A', 'B', 'C']))
  })

  it('returns a header-only file for an empty key list', () => {
    const content = generateEnvExample([])
    expect(content).not.toMatch(/^[A-Z_]+=/m)
    expect(content.startsWith('# Generated by EnvMirror')).toBe(true)
  })
})
