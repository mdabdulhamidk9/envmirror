/**
 * Safe `.env.example` generator. Produces variable NAMES only, with empty
 * placeholder values, deduplicated and alphabetically ordered. Secret values
 * can never reach this module because the parser discards them by design —
 * but an allow-list filter is applied as defense in depth.
 */
import type { EnvId } from '../types'
import { ENV_IDS } from './compare'

const SAFE_KEY_PATTERN = /^[A-Za-z_][A-Za-z0-9_]*$/

/**
 * Collect the union of key names across the provided environments.
 * Deterministic: alphabetically sorted, deduplicated.
 */
export function collectUnionKeys(keysByEnv: Record<EnvId, readonly string[]>): string[] {
  const names = new Set<string>()
  for (const id of ENV_IDS) {
    for (const name of keysByEnv[id]) names.add(name)
  }
  return [...names].sort((a, b) => a.localeCompare(b))
}

/** Keep only syntactically safe, unique key names (defense in depth). */
export function sanitizeKeyNames(keyNames: readonly string[]): string[] {
  return [...new Set(keyNames)].filter((name) => SAFE_KEY_PATTERN.test(name))
}

/**
 * Generate the `.env.example` content: one `KEY=` line per unique name,
 * alphabetically ordered, with an explanatory header. Never includes values.
 */
export function generateEnvExample(keyNames: readonly string[]): string {
  const names = sanitizeKeyNames(keyNames).sort((a, b) => a.localeCompare(b))
  const lines = [
    '# Generated by EnvMirror — variable names only, no secret values.',
    '# Fill in a value for each variable in the target environment.',
    '',
    ...names.map((name) => `${name}=`),
  ]
  return lines.join('\n') + (names.length > 0 ? '\n' : '')
}
